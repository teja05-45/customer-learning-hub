"""Password hashing and session tokens.

Deliberately dependency-free: PBKDF2-HMAC-SHA256 from the standard library is
adequate for an internal tool and avoids adding a crypto package to the demo.
Session tokens are random, stored only as a digest, and delivered in an
HTTP-only cookie.
"""

import hashlib
import hmac
import secrets

SESSION_COOKIE = "clh_session"
SESSION_HOURS = 8
PBKDF2_ITERATIONS = 260_000
DEMO_PASSWORD = "demo-password"


def hash_password(password: str) -> str:
    salt = secrets.token_bytes(16)
    digest = hashlib.pbkdf2_hmac("sha256", password.encode("utf-8"), salt, PBKDF2_ITERATIONS)
    return f"pbkdf2_sha256${PBKDF2_ITERATIONS}${salt.hex()}${digest.hex()}"


def verify_password(password: str, stored: str | None) -> bool:
    if not stored:
        return False
    try:
        algorithm, iterations, salt_hex, digest_hex = stored.split("$", 3)
        if algorithm != "pbkdf2_sha256":
            return False
        expected = bytes.fromhex(digest_hex)
        actual = hashlib.pbkdf2_hmac(
            "sha256", password.encode("utf-8"), bytes.fromhex(salt_hex), int(iterations)
        )
    except (ValueError, TypeError):
        return False
    return hmac.compare_digest(actual, expected)


def new_session_token() -> str:
    return secrets.token_urlsafe(32)


def token_digest(token: str) -> str:
    return hashlib.sha256(token.encode("utf-8")).hexdigest()
